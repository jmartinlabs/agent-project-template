#!/bin/bash
# Hermes P-ISO — isolation proof for the eval runner. No model calls, no network.
#
#   bash evals/results/2026-11-10-hermes-piso-probe-v2.sh <origin-repo> <work-dir>
#
# v2: every write attempt targets a disposable location. The real checkout and the real profile
# are never written to, not even by a probe that expects denial, and the config A/B uses a
# synthetic config.yaml instead of a copy of the user's. The real paths are covered by a static
# allow-list assertion plus a writability check (A11); the denial itself is demonstrated on decoy
# paths with the same shape. The original probe is kept unchanged as the historical record.
#
# Proves four things the adapter document claims, in this order:
#   A. the OS sandbox really denies writes outside the fixture (with A/B controls);
#   B. the tool surface a runner gets from `-t <toolset>` (composed by the runtime itself);
#   C. the pre/post manifest detects a planted mutation, including one a timestamp check misses;
#   D. origin repository and real profile untouched.
# Every assertion appends one `CHECK <id> PASS|FAIL <detail>` line to the log; the summary is
# generated by parsing that log, never by transcription. Exit: 0 all pass, 1 any fail, 3 blocked.
set -u
ORIG=$(cd "${1:?usage: probe.sh <origin-repo> <work-dir>}" && pwd -P)
ROOT=${2:?usage: probe.sh <origin-repo> <work-dir>}
mkdir -p "$ROOT" || exit 3
ROOT=$(cd "$ROOT" && pwd -P)
FIX="$ROOT/fixture/agent-project-template"
WORK="$ROOT/run"; TMP="$ROOT/tmp"; ESCAPE="$ROOT/escape"; DECOY="$ROOT/decoy-home"
DORIG="$ROOT/decoy-origin"; DPROFILE="$ROOT/decoy-profile-home"
LOG="$ROOT/piso.log"
REALHOME="$HOME/.hermes"
TOTAL=0; FAILS=0; BLOCKED=0
: > "$LOG"

log() { printf '%s\n' "$*"; printf '%s\n' "$*" >> "$LOG"; }
say() { log ""; log "===== $1 ====="; }
check() { # id status detail
  TOTAL=$((TOTAL+1))
  if [ "$2" = PASS ]; then log "CHECK $1 PASS ${3:-}"; else log "CHECK $1 FAIL ${3:-}"; FAILS=$((FAILS+1)); fi
}
blocked() { TOTAL=$((TOTAL+1)); BLOCKED=$((BLOCKED+1)); log "CHECK $1 BLOCKED $2"; }
run() { log ""; log "\$ $*"; "$@" 2>&1 | sed 's/^/    /'; return ${PIPESTATUS[0]}; }

mkdir -p "$WORK" "$TMP" "$ESCAPE" "$DECOY" "$DORIG" "$DPROFILE" "$ROOT/fixture"

say "0. environment"
log "date_local=$(date +%Y-%m-%dT%H:%M:%S%z)"
log "os=$(sw_vers -productVersion) arch=$(uname -m)"
log "hermes=$(hermes --version 2>&1 | head -1)"
log "home=$HOME"
log "origin=$ORIG"
log "work=$ROOT"

say "1. origin + real profile BEFORE"
hashes() { ( cd "$ORIG" && shasum -a 256 AGENTS.md README.md specs/methodology/approvals.md \
  .agents/skills/*/SKILL.md ) | sed "s|$ORIG/||"; }
hashes > "$ROOT/origin-hashes-before.txt"
log "origin_head=$(cd "$ORIG" && git rev-parse HEAD)"
log "origin_sha256_of_13_files=$(wc -l < "$ROOT/origin-hashes-before.txt" | tr -d ' ')"
log "real_config_sha256=$(shasum -a 256 "$REALHOME/config.yaml" | awk '{print $1}')"
log "real_trusted_dirs=$(env -u HERMES_HOME hermes config get skills.trusted_project_dirs | tr '\n' ' ')"

say "2. disposable clone"
if [ ! -d "$FIX/.git" ]; then
  run git clone --quiet --no-hardlinks "$ORIG" "$FIX"
fi
log "fixture_head=$(cd "$FIX" && git rev-parse HEAD)"
log "fixture_claude_wrappers=$(find "$FIX/.claude/skills" -name SKILL.md | wc -l | tr -d ' ')"
log "fixture_canonical_skills=$(find "$FIX/.agents/skills" -name SKILL.md | wc -l | tr -d ' ')"

say "3. sandbox profiles"
cat > "$WORK/piso.sb" <<EOF
(version 1)
(allow default)
(deny file-write*)
(allow file-write*
  (subpath "$FIX")
  (subpath "$WORK")
  (subpath "$TMP")
  (literal "/dev/null")
  (literal "/dev/zero")
  (subpath "/dev/fd"))
EOF
# A/B control: identical profile plus an explicit allow for the escape directory.
cat > "$WORK/piso-allow-escape.sb" <<EOF
(version 1)
(allow default)
(deny file-write*)
(allow file-write*
  (subpath "$FIX")
  (subpath "$WORK")
  (subpath "$TMP")
  (subpath "$ESCAPE")
  (literal "/dev/null")
  (literal "/dev/zero")
  (subpath "/dev/fd"))
EOF
# Per-file deny: the runner's own config-write path must fail even when its home is writable.
cat > "$WORK/piso-decoy-home.sb" <<EOF
(version 1)
(allow default)
(deny file-write*)
(allow file-write*
  (subpath "$FIX")
  (subpath "$WORK")
  (subpath "$TMP")
  (subpath "$DECOY")
  (literal "/dev/null")
  (literal "/dev/zero")
  (subpath "/dev/fd"))
(deny file-write* (literal "$DECOY/config.yaml"))
EOF
cat "$WORK/piso.sb" >> "$LOG"

if command -v sandbox-exec > /dev/null 2>&1; then
  check A1 PASS "sandbox-exec=$(command -v sandbox-exec)"
else
  blocked A1 "sandbox-exec unavailable: no OS write jail on this host; not substituting a weaker control"
fi
if [ "$BLOCKED" -gt 0 ]; then
  log "RESULT BLOCKED $((TOTAL-FAILS-BLOCKED))/$TOTAL checks pass, $BLOCKED blocked"
  exit 3
fi

if sandbox-exec -f "$WORK/piso.sb" /usr/bin/true 2> "$ROOT/profile-error.txt"; then
  check A2 PASS "profile compiles and executes"
else
  check A2 FAIL "profile rejected: $(head -2 "$ROOT/profile-error.txt" | tr '\n' ' ')"
fi

say "4. A. sandbox denies writes outside the fixture (decoys only, no real path written)"
SX() { TMPDIR="$TMP" sandbox-exec -f "$1" /bin/sh -c "$2"; }

SX "$WORK/piso.sb" "printf ok > '$FIX/inside.txt'" > /dev/null 2>&1
if [ "$(cat "$FIX/inside.txt" 2>/dev/null)" = ok ]; then check A3 PASS "write inside fixture allowed"; else check A3 FAIL "fixture write blocked"; fi

printf 'decoy checkout\n' > "$DORIG/AGENTS.md"
if SX "$WORK/piso.sb" "printf x > '$DORIG/PISO_ESCAPE.txt'" > "$ROOT/a4.txt" 2>&1; then A4EXIT=0; else A4EXIT=$?; fi
if [ -e "$DORIG/PISO_ESCAPE.txt" ]; then rm -f "$DORIG/PISO_ESCAPE.txt"; check A4 FAIL "decoy checkout write succeeded; file removed"; else
  if [ "$A4EXIT" -ne 0 ] && grep -qi "operation not permitted\|deny" "$ROOT/a4.txt"; then
    check A4 PASS "write to a checkout-shaped decoy denied (exit=$A4EXIT, path writable without the jail=$(test -w "$DORIG" && echo yes || echo no))"
  else
    check A4 FAIL "decoy checkout write not denied as expected (exit=$A4EXIT)"
  fi
fi

if SX "$WORK/piso.sb" "printf x > '$DPROFILE/PISO_ESCAPE.txt'" > /dev/null 2>&1; then A5EXIT=0; else A5EXIT=$?; fi
if [ -e "$DPROFILE/PISO_ESCAPE.txt" ]; then rm -f "$DPROFILE/PISO_ESCAPE.txt"; check A5 FAIL "decoy profile-home write succeeded; file removed"; else
  [ "$A5EXIT" -ne 0 ] && check A5 PASS "write to a profile-home-shaped decoy denied (exit=$A5EXIT)" || check A5 FAIL "not denied (exit=$A5EXIT)"
fi

if SX "$WORK/piso.sb" "printf x > /tmp/piso-escape-$$.txt" > /dev/null 2>&1; then A6EXIT=0; rm -f "/tmp/piso-escape-$$.txt"; else A6EXIT=$?; fi
[ "$A6EXIT" -ne 0 ] && check A6 PASS "/tmp write denied (exit=$A6EXIT)" || check A6 FAIL "/tmp write allowed"

rm -f "$FIX/escape-link"
ln -s "$DORIG" "$FIX/escape-link"
if SX "$WORK/piso.sb" "printf x > '$FIX/escape-link/PISO_ESCAPE.txt'" > /dev/null 2>&1; then A7EXIT=0; else A7EXIT=$?; fi
if [ -e "$DORIG/PISO_ESCAPE.txt" ]; then rm -f "$DORIG/PISO_ESCAPE.txt"; check A7 FAIL "symlink escape succeeded; file removed"; else
  [ "$A7EXIT" -ne 0 ] && check A7 PASS "symlink traversal denied (exit=$A7EXIT)" || check A7 FAIL "symlink traversal allowed"
fi
rm -f "$FIX/escape-link"

# A/B: the same path is writable without the profile, and writable with the profile that names it.
rm -f "$ESCAPE/canary.txt"
if printf canary > "$ESCAPE/canary.txt" 2>/dev/null; then check A8a PASS "escape path writable with no sandbox"; else check A8a FAIL "escape path not writable even unsandboxed"; fi
rm -f "$ESCAPE/canary.txt"
if SX "$WORK/piso.sb" "printf canary > '$ESCAPE/canary.txt'" > /dev/null 2>&1; then
  [ -e "$ESCAPE/canary.txt" ] && check A8b FAIL "profile did not deny an allowed-nowhere path" || check A8b FAIL "denied but file exists"
else
  [ -e "$ESCAPE/canary.txt" ] && check A8b FAIL "denied with exit!=0 but file was created" || check A8b PASS "same path denied by the profile"
fi
rm -f "$ESCAPE/canary.txt"
if SX "$WORK/piso-allow-escape.sb" "printf canary > '$ESCAPE/canary.txt'" > /dev/null 2>&1 && [ -e "$ESCAPE/canary.txt" ]; then
  check A8c PASS "allow rule makes the path writable again: the denial is the rule, not the environment"
else
  check A8c FAIL "allow rule did not restore the write"
fi
rm -f "$ESCAPE/canary.txt"

# A/B on the runner's real write path: `hermes config set` writes $HERMES_HOME/config.yaml.
# The config is synthetic: same file, same write path, none of the user's settings.
printf 'display:\n  skin: default\nmodel:\n  default: synthetic/none\n' > "$DECOY/config.yaml"
DECOY_BEFORE=$(shasum -a 256 "$DECOY/config.yaml" | awk '{print $1}')
SX "$WORK/piso-decoy-home.sb" "HERMES_HOME='$DECOY' TERMINAL_CWD='$FIX' hermes config set display.piso_canary $(date +%s)" > "$ROOT/a9-sandboxed.txt" 2>&1
A9EXIT=$?
DECOY_AFTER=$(shasum -a 256 "$DECOY/config.yaml" | awk '{print $1}')
if [ "$DECOY_BEFORE" = "$DECOY_AFTER" ]; then
  check A9a PASS "sandboxed config write left the synthetic config byte-identical (hermes exit=$A9EXIT)"
else
  check A9a FAIL "sandboxed config write changed the decoy config"
fi
printf 'display:\n  skin: default\nmodel:\n  default: synthetic/none\n' > "$DECOY/config.yaml"
env HERMES_HOME="$DECOY" TERMINAL_CWD="$FIX" hermes config set display.piso_canary "$(date +%s)" > "$ROOT/a9-control.txt" 2>&1
DECOY_CONTROL=$(shasum -a 256 "$DECOY/config.yaml" | awk '{print $1}')
if [ "$DECOY_BEFORE" != "$DECOY_CONTROL" ]; then
  check A9b PASS "control without the sandbox changes the synthetic config: the deny rule is what blocked it"
else
  check A9b FAIL "control did not change the config; the sandboxed result proves nothing"
fi

if SX "$WORK/piso.sb" "cat '$ORIG/AGENTS.md'" > /dev/null 2>&1; then check A10 PASS "reads outside the write jail stay allowed"; else check A10 FAIL "read denied: the runner would be unusable"; fi

# A11 covers the real paths without aiming a write at them: the generated allow list must not
# contain the real checkout or the real profile, and both must be writable outside the jail, so a
# write there would be denied by the rule rather than by permissions.
if ! grep -q "subpath \"$ORIG\"" "$WORK/piso.sb" && ! grep -q "subpath \"$REALHOME\"" "$WORK/piso.sb" \
   && [ -w "$ORIG" ] && [ -w "$REALHOME" ]; then
  check A11 PASS "real checkout and real profile are outside every allow rule and writable without the jail"
else
  check A11 FAIL "real-path coverage assertion did not hold"
fi

say "5. B. tool surface composed by the runtime"
PY=$(ls -d "$HOME"/.hermes/tools/python-3.*/bin/python3 2>/dev/null | head -1)
DEPS=$(ls -d "$HOME"/.hermes/cache/uv/archive-v0/*/ 2>/dev/null | tr '\n' ':')
if [ -n "${PY:-}" ] && [ -n "${DEPS:-}" ]; then
  ( cd "$FIX" && TERMINAL_CWD="$FIX" PYTHONPATH="$REALHOME/hermes-agent:$DEPS" "$PY" - "$ROOT" <<'PY'
import json, sys
from pathlib import Path
out = Path(sys.argv[1])
from toolsets import TOOLSETS, resolve_toolset
import model_tools
res = {
    "file_tools": TOOLSETS["file"]["tools"],
    "file_resolved": sorted(resolve_toolset("file")),
    "vision_surface": sorted(t["function"]["name"] for t in
        model_tools.get_tool_definitions(enabled_toolsets=["vision"], quiet_mode=True)),
}
print(json.dumps(res))
(out / "b-surface.json").write_text(json.dumps(res, indent=1) + "\n", encoding="utf-8")
PY
  ) >> "$LOG" 2>&1
else
  log "python_or_deps_missing"
fi
if [ -f "$ROOT/b-surface.json" ]; then
  log "surface=$(tr -d '\n' < "$ROOT/b-surface.json")"
  python3 - "$ROOT/b-surface.json" "$LOG" <<'PY'
import json, sys
d = json.load(open(sys.argv[1])); log = open(sys.argv[2], "a")
def chk(cid, ok, detail):
    log.write(f"CHECK {cid} {'PASS' if ok else 'FAIL'} {detail}\n")
expected = {"read_file", "write_file", "patch", "search_files"}
chk("B1", set(d["file_tools"]) == expected, f"file toolset={d['file_tools']}")
chk("B2", set(d["file_resolved"]) == expected, f"resolved={d['file_resolved']}")
mutating = {"terminal","process_manage","write_file","patch","execute_code","skill_manage",
            "delegate_task","cronjob_manage","browser_exec","computer_use","memory","todo_list"}
chk("B3", d["vision_surface"] == ["vision_analyze"], f"vision surface={d['vision_surface']}")
chk("B4", not (mutating & set(d["vision_surface"])), f"mutating tools in vision surface={sorted(mutating & set(d['vision_surface']))}")
PY
  TOTAL=$((TOTAL+4))
  FAILS=$((FAILS + $(grep -c '^CHECK B[1-4] FAIL' "$LOG")))
else
  for i in B1 B2 B3 B4; do blocked $i "could not import the runtime out of band"; done
fi

say "6. C. the manifest detects a planted mutation"
manifest() { ( cd "$FIX" && { echo "head=$(git rev-parse HEAD)"; git status --porcelain; \
  find . -path ./.git -prune -o -type f -print0 | xargs -0 shasum -a 256 | LC_ALL=C sort; } ); }
manifest > "$ROOT/m0.txt"
manifest > "$ROOT/m0b.txt"
if diff -q "$ROOT/m0.txt" "$ROOT/m0b.txt" > /dev/null; then check C0 PASS "clean tree: manifest stable across two reads ($(wc -l < "$ROOT/m0.txt" | tr -d ' ') lines)"; else check C0 FAIL "manifest is not deterministic"; fi

printf '\n' >> "$FIX/AGENTS.md"
manifest > "$ROOT/m1.txt"
# One changed path means one hash pair (<, >) plus, when the tree was clean, one porcelain row.
C1_PATHS=$(diff "$ROOT/m0.txt" "$ROOT/m1.txt" | grep -E '^[<>] [0-9a-f]{64}  ' | awk '{print $3}' | sort -u)
C1_COUNT=$(printf '%s\n' "$C1_PATHS" | grep -c . )
if [ "$C1_COUNT" -eq 1 ] && [ "$C1_PATHS" = "./AGENTS.md" ]; then
  check C1 PASS "one appended byte in AGENTS.md -> exactly one changed path ($(diff "$ROOT/m0.txt" "$ROOT/m1.txt" | grep -cE '^[<>] [0-9a-f]{64}  ') hash rows + $( ( cd "$FIX" && git status --porcelain | wc -l | tr -d ' ' ) ) porcelain row)"
else
  check C1 FAIL "changed paths=$C1_COUNT [$C1_PATHS]"
fi
( cd "$FIX" && git checkout -- AGENTS.md )
manifest > "$ROOT/m2.txt"
diff -q "$ROOT/m0.txt" "$ROOT/m2.txt" > /dev/null && check C2 PASS "revert restores the exact baseline" || check C2 FAIL "baseline not restored"

printf 'injected\n' > "$FIX/INJECTED.txt"
manifest > "$ROOT/m3.txt"
if diff "$ROOT/m0.txt" "$ROOT/m3.txt" | grep -q 'INJECTED.txt' && ( cd "$FIX" && git status --porcelain | grep -q 'INJECTED.txt' ); then
  check C3 PASS "untracked file detected by porcelain and by content hashes"
else
  check C3 FAIL "untracked file missed"
fi
rm -f "$FIX/INJECTED.txt"

# Same size, restored mtime: content hashing must catch what a timestamp check does not.
( cd "$FIX" && touch -r AGENTS.md "$ROOT/mtime-ref" && stat -f '%z %m' AGENTS.md > "$ROOT/stat-before.txt" )
( cd "$FIX" && printf 'X' | dd of=AGENTS.md bs=1 seek=0 conv=notrunc 2>/dev/null && touch -r "$ROOT/mtime-ref" AGENTS.md && stat -f '%z %m' AGENTS.md > "$ROOT/stat-after.txt" )
manifest > "$ROOT/m4.txt"
SIZE_SAME=$(cmp -s "$ROOT/stat-before.txt" "$ROOT/stat-after.txt" && echo yes || echo no)
MTIME_MISS=$(find "$FIX" -path "$FIX/.git" -prune -o -newer "$ROOT/mtime-ref" -name 'AGENTS.md' -print | wc -l | tr -d ' ')
C4=$(diff "$ROOT/m0.txt" "$ROOT/m4.txt" | grep -c '^[<>]')
if [ "$SIZE_SAME" = yes ] && [ "$MTIME_MISS" -eq 0 ] && [ "$C4" -gt 0 ]; then
  check C4 PASS "size and mtime identical, sha256 still catches the flip ($C4 diff lines)"
else
  check C4 FAIL "size_same=$SIZE_SAME newer_hits=$MTIME_MISS diff=$C4"
fi
( cd "$FIX" && git checkout -- AGENTS.md )
manifest > "$ROOT/m5.txt"
diff -q "$ROOT/m0.txt" "$ROOT/m5.txt" > /dev/null && check C5 PASS "fixture restored to the baseline manifest" || check C5 FAIL "fixture not restored"

say "7. D. origin and real profile untouched"
hashes > "$ROOT/origin-hashes-after.txt"
diff -q "$ROOT/origin-hashes-before.txt" "$ROOT/origin-hashes-after.txt" > /dev/null \
  && check D1 PASS "origin content hashes identical before/after" || check D1 FAIL "origin content changed"
log "origin_head_after=$(cd "$ORIG" && git rev-parse HEAD)"
log "origin_status_after=$(cd "$ORIG" && git status --porcelain | tr '\n' ';')"
REAL_AFTER=$(shasum -a 256 "$REALHOME/config.yaml" | awk '{print $1}')
REAL_TRUST=$(env -u HERMES_HOME hermes config get skills.trusted_project_dirs | tr '\n' ' ')
if [ "$REAL_AFTER" = "$(grep '^real_config_sha256=' "$LOG" | head -1 | cut -d= -f2)" ] && [ "$REAL_TRUST" = "[] " ]; then
  check D2 PASS "real profile config unchanged, trusted_project_dirs still empty"
else
  check D2 FAIL "real profile changed (trust='$REAL_TRUST')"
fi
rm -f "$FIX/inside.txt"
if [ -z "$(cd "$FIX" && git status --porcelain)" ]; then
  check D3 PASS "fixture working tree clean"
else
  ( cd "$FIX" && git status --porcelain ); check D3 FAIL "fixture dirty"
fi
log "model_calls=0 network_calls=0 hermes_invocations=$(grep -c '^\$ .*hermes ' "$LOG" || true)"

say "8. result"
PASSED=$((TOTAL-FAILS))
log "CHECKS total=$TOTAL pass=$PASSED fail=$FAILS blocked=$BLOCKED"
if [ "$FAILS" -eq 0 ]; then log "RESULT PASS ${PASSED}/${TOTAL}"; exit 0; else log "RESULT FAIL ${PASSED}/${TOTAL}"; exit 1; fi
